// Writes the custom migration (supabase/migrations/*_private_triggers_and_grants.sql) from the
// schema: the private schema and its two trigger functions, one touch trigger per table with an
// updated_at column, the auth.users trigger, and table grants derived from each table's policies.
//   pnpm --filter @singology/db generate --custom --name private_triggers_and_grants
//   pnpm --filter @singology/db generate:private
import { readdirSync, writeFileSync } from "node:fs";

import { is } from "drizzle-orm";
import { getTableConfig, PgTable } from "drizzle-orm/pg-core";

import * as schema from "../src/schema";

const MIGRATIONS_DIR = new URL("../../../supabase/migrations/", import.meta.url);
const GRANTEES = ["anon", "authenticated"] as const;
const VERBS = ["select", "insert", "update", "delete"] as const;

type Grantee = (typeof GRANTEES)[number];
type Verb = (typeof VERBS)[number];

const FIXED = `-- Generated by packages/db/scripts/privateMigration.ts from the schema; do not edit by hand.

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
--> statement-breakpoint

create function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
--> statement-breakpoint

-- Runs as its owner because the inserting role (supabase_auth_admin) cannot write public.profiles.
create function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(new.email, '@', 1))
  );
  return new;
end;
$$;
--> statement-breakpoint

revoke all on function private.touch_updated_at() from public, anon, authenticated;
revoke all on function private.handle_new_user() from public, anon, authenticated;
--> statement-breakpoint

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();
--> statement-breakpoint
`;

function roleNames(to: unknown): string[] {
  return [to].flat().map((role) => {
    if (typeof role === "string") {
      return role;
    }
    if (
      typeof role === "object" &&
      role !== null &&
      "name" in role &&
      typeof role.name === "string"
    ) {
      return role.name;
    }
    throw new Error(`Unrecognised policy role: ${String(role)}`);
  });
}

const isGrantee = (role: string): role is Grantee => (GRANTEES as readonly string[]).includes(role);

function verbsOf(policyFor: string | undefined): Verb[] {
  return policyFor === undefined || policyFor === "all" ? [...VERBS] : [policyFor as Verb];
}

const tables = Object.values(schema)
  .filter((value) => is(value, PgTable))
  .map((table) => getTableConfig(table))
  .sort((a, b) => a.name.localeCompare(b.name));

const touchTriggers = tables
  .filter((table) => table.columns.some((column) => column.name === "updated_at"))
  .map(
    (table) =>
      `create trigger touch_updated_at before update on public.${table.name}\n` +
      `  for each row execute function private.touch_updated_at();\n--> statement-breakpoint\n`,
  );

const grants = tables.flatMap((table) =>
  GRANTEES.flatMap((grantee) => {
    const verbs = new Set(
      table.policies
        .filter((policy) => roleNames(policy.to).filter(isGrantee).includes(grantee))
        .flatMap((policy) => verbsOf(policy.for)),
    );
    const ordered = VERBS.filter((verb) => verbs.has(verb));
    return ordered.length === 0
      ? []
      : [`grant ${ordered.join(", ")} on public.${table.name} to ${grantee};`];
  }),
);

const sql =
  FIXED +
  "\n" +
  touchTriggers.join("") +
  "\n-- RLS decides which rows; these grants decide which statements, derived from each table's\n" +
  "-- policies. A table without policies (notifications) gets none, and postgres keeps everything.\n" +
  "revoke all on all tables in schema public from anon, authenticated;\n" +
  "grant usage on schema public to anon, authenticated;\n" +
  "--> statement-breakpoint\n\n" +
  grants.join("\n") +
  "\n";

const targets = readdirSync(MIGRATIONS_DIR).filter((file) =>
  file.endsWith("_private_triggers_and_grants.sql"),
);
if (targets.length !== 1 || targets[0] === undefined) {
  throw new Error(`Expected one *_private_triggers_and_grants.sql, found ${targets.length}.`);
}
writeFileSync(new URL(targets[0], MIGRATIONS_DIR), sql, "utf8");
console.log(
  `Wrote ${targets[0]}: ${touchTriggers.length} touch triggers, ${grants.length} grants.`,
);
